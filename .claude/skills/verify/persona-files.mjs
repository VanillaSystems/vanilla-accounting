// Made-up files of a persona for persona tests, as `vm.sh up` puts them into the VM's ~/Downloads.
//
//   node persona-files.mjs OUT [--persona NAME]     the files into OUT, persona.env (and answer-key.md) beside it
//   node persona-files.mjs --key NAME [--write]     print the persona's answer key; --write puts its summary into
//                                                   its scenario (the scenario is public: whole francs only, the key stays local)
//   node persona-files.mjs --list                    the personas' names
//
// NAME (also $PERSONA) is one of PERSONAS, huber by default. A persona is a module in persona-files/
// whose default export build() returns { files, docs, photos, copies, env, key?, summary? }: text files by
// name, HTML that becomes a PDF (docs) or a JPEG phone photo (photos), copies of a generated file (a
// duplicate), the lines of persona.env, the tester's answer key as markdown, and the few lines of it in whole
// francs that its public scenario may hold (check-public refuses amounts with cents in prose). Another
// persona is one more entry here and one module beside the others (shared helpers: persona-files/kit.mjs).
import puppeteer from 'puppeteer-core';
import fs from 'fs';

const PERSONAS = {
  // Malerei Huber GmbH: a painting firm, effective method, quarterly (personas/first-run.md).
  huber: { module: './persona-files/huber.mjs' },
  // Teegarten Wyss GmbH: a webshop on Shopify, payouts over a clearing account (personas/first-run-webshop.md).
  webshop: { module: './persona-files/webshop.mjs', scenario: 'personas/first-run-webshop.md' },
  // Kälin Advisory GmbH: a one-person consultancy, Bezugsteuer and private outlays (personas/first-run-consulting.md).
  consulting: { module: './persona-files/consulting.mjs', scenario: 'personas/first-run-consulting.md' },
};

const args = process.argv.slice(2);
if (args[0] === '--list') { console.log(Object.keys(PERSONAS).join('\n')); process.exit(0); }
const flag = (name) => { const i = args.indexOf(name); return i >= 0 ? args.splice(i, 2)[1] : undefined; };
const keyOf = flag('--key');
const write = args.includes('--write') && args.splice(args.indexOf('--write'), 1);
const name = flag('--persona') ?? keyOf ?? process.env.PERSONA ?? 'huber';
const entry = PERSONAS[name];
if (!entry) { console.error(`no persona ${name}: ${Object.keys(PERSONAS).join(', ')}`); process.exit(1); }
const persona = (await import(new URL(entry.module, import.meta.url))).default();

const BEGIN = '<!-- answer key: generated by persona-files.mjs --key, do not edit by hand -->';
const END = '<!-- end of answer key -->';
if (keyOf) {
  if (!persona.key) { console.error(`persona ${name} has no answer key`); process.exit(1); }
  if (!write) { console.log(persona.key); process.exit(0); }
  const md = new URL(entry.scenario, import.meta.url);
  const text = fs.readFileSync(md, 'utf8');
  const a = text.indexOf(BEGIN), b = text.indexOf(END);
  if (a < 0 || b < a) { console.error(`${entry.scenario} has no answer key markers`); process.exit(1); }
  fs.writeFileSync(md, `${text.slice(0, a + BEGIN.length)}\n${persona.summary}\n${text.slice(b)}`);
  console.log(`answer key summary written into ${entry.scenario}`);
  process.exit(0);
}

const OUT = args[0];
if (!OUT) { console.error('usage: node persona-files.mjs OUT [--persona NAME]'); process.exit(1); }
fs.mkdirSync(OUT, { recursive: true });
for (const [f, body] of Object.entries(persona.files)) fs.writeFileSync(`${OUT}/${f}`, body);
const b = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const p = await b.newPage();
for (const [f, html] of Object.entries(persona.docs)) { await p.setContent(html); await p.pdf({ path: `${OUT}/${f}`, format: 'A4' }); }
for (const [f, html] of Object.entries(persona.photos)) { await p.setViewport({ width: 600, height: 900 }); await p.setContent(html); await p.screenshot({ path: `${OUT}/${f}`, type: 'jpeg', quality: 70 }); }
await b.close();
for (const [to, from] of persona.copies ?? []) fs.copyFileSync(`${OUT}/${from}`, `${OUT}/${to}`);
fs.writeFileSync(`${OUT}/../persona.env`, persona.env);
if (persona.key) fs.writeFileSync(`${OUT}/../answer-key.md`, `${persona.key}\n`);
console.log(OUT);
