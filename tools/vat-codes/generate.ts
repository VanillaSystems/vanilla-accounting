/**
 * npm run vat-codes
 *
 * Writes the two derived files of the VAT-code catalogue:
 * - src/accounting/vat-codes.source.ts: Banana's code list (reference/MWST-codes.txt) and, per
 *   code, the casebook lines that use it (examples/cases/), as data the browser can import.
 * - docs/vat-codes.md: the catalogue (src/accounting/vat-codes.ts) for people, in English.
 *
 * tests/vat-codes.test.ts fails while either file differs from what this script writes.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { loadCases } from '../../src/knowledge/cases.js';
import { APP_ROOT } from '../../src/workspace/workspace.js';
import type { Messages } from '../../src/app/i18n/types.js';
import { loadJurisdiction } from '../../src/core/modules/load.js';
import { setJurisdiction } from '../../src/engines/index.js';

// The catalogue is the shipped jurisdiction's, for a firm on the effective method.
setJurisdiction(loadJurisdiction(APP_ROOT, 'ch').jurisdiction);

export const SOURCE_FILE = join(APP_ROOT, 'src/accounting/vat-codes.source.ts');
export const DOCS_FILE = join(APP_ROOT, 'docs/vat-codes.md');

interface BananaRow { code: string; text: string; ziffern: string[]; rate?: number; amountType?: '1' | '2' }

/** The code rows of Banana's list: a tab, the code, its text, the group, the Ziffern, …, amount type, rate. */
function bananaRows(): BananaRow[] {
  const lines = readFileSync(join(APP_ROOT, 'reference/MWST-codes.txt'), 'utf8').split(/\r?\n/);
  return lines.map((l) => l.split('\t')).filter((c) => c[0] === '' && c[1] && c[3] !== undefined).map((c) => {
    const rate = c[7] ? Number(c[7]) : undefined;
    const amountType = c[6] === '1' || c[6] === '2' ? c[6] : undefined;
    return {
      code: c[1],
      text: c[2].replace(/\s+/g, ' ').trim(),
      ziffern: (c[4] ?? '').split(';').filter((z) => /^\d+$/.test(z)),
      ...(rate !== undefined ? { rate } : {}),
      ...(amountType ? { amountType } : {}),
    };
  });
}

/** Per unsigned code, the casebook lines that use it: the plain code's cases first, then its minus form's. */
function caseExamples() {
  const byCode: Record<string, Array<Record<string, unknown> & { negative: boolean }>> = {};
  for (const c of loadCases()) {
    for (const l of c.lines) {
      if (!l.vatCode) continue;
      const code = l.vatCode.replace(/^-/, '');
      (byCode[code] ??= []).push({
        caseId: c.id, title: c.title, debit: l.debit, credit: l.credit, amount: l.amount,
        ...(l.currency ? { currency: l.currency } : {}), vatCode: l.vatCode, description: l.description,
        negative: l.vatCode.startsWith('-'),
      });
    }
  }
  return Object.fromEntries(Object.entries(byCode).sort(([a], [b]) => a.localeCompare(b))
    .map(([code, list]) => [code, [...list.filter((e) => !e.negative), ...list.filter((e) => e.negative)].map(({ negative: _, ...e }) => e)]));
}

export function renderSource(): string {
  return `/** Generated by \`npm run vat-codes\` from reference/MWST-codes.txt and examples/cases/. Do not edit. */

/** One row of Banana's VAT-code list: its German text, the Ziffern Banana declares it in, rate and amount type. */
export interface BananaVatCode {
  code: string;
  text: string;
  ziffern: readonly string[];
  rate?: number;
  /** '1': the amount is net (VAT excluded); '2': the amount is the VAT itself. */
  amountType?: '1' | '2';
}

/** A casebook line (examples/cases/<caseId>.yaml) that uses a code. */
export interface VatCodeExample {
  caseId: string;
  title: string;
  debit: string;
  credit: string;
  amount: number;
  currency?: string;
  vatCode: string;
  description: string;
}

export const BANANA_VAT_CODES: readonly BananaVatCode[] = ${JSON.stringify(bananaRows(), null, 2)};

/** Per unsigned code. */
export const VAT_CODE_EXAMPLES: Readonly<Record<string, readonly VatCodeExample[]>> = ${JSON.stringify(caseExamples(), null, 2)};
`;
}

/** docs/vat-codes.md, from the catalogue and the English texts. */
export async function renderDocs(): Promise<string> {
  const { vatCodes, VAT_CODE_FAMILIES, VAT_CODE_KINDS, vatCodeName, vatCodeRateName } = await import('../../src/accounting/vat-codes.js');
  (await import('../../src/workspace/workspace.js')).workspaceAt(join(APP_ROOT, 'demo'));
  const VAT_CODES = vatCodes();
  const en = ((await import('../../src/app/i18n/locales/en.js')) as { default: { messages: Messages } }).default.messages;
  const text = (key: string, vars: Record<string, string | number> = {}) =>
    String(en[key as keyof Messages]).replace(/\{(\w+)\}/g, (_, n: string) => String(vars[n]));
  const RATE_NAMES: Record<string, string> = { Normalsatz: 'vat.rateStandard', 'Reduzierter Satz': 'vat.rateReduced', Beherbergungssatz: 'vat.rateAccommodation' };
  const md = (s: string) => s.replace(/\|/g, '\\|');

  const zifferCell = (c: (typeof VAT_CODES)[number]) => {
    if (!c.ziffern) return `not declared (Banana: ${c.bananaZiffern.join(', ') || 'none'})`;
    if (c.ziffern.length === 0) return 'none';
    return c.ziffern.map((z) => `${z.ziffer} (${z.figure})`).join(', ');
  };
  const amountCell = (c: (typeof VAT_CODES)[number]) => ({ gross: 'gross', net: 'net', tax: 'the VAT' } as const)[c.amountIs];
  const rateCell = (c: (typeof VAT_CODES)[number]) => {
    if (c.rate === null) return '';
    const name = vatCodeRateName(c.rate);
    return `${c.rate}%${name ? ` ${text(RATE_NAMES[name]).toLowerCase()}` : ''}${c.superseded ? ' (until 2023)' : ''}`;
  };

  const out: string[] = [
    '# VAT codes (MWST-Codes)',
    '',
    '<!-- Generated by `npm run vat-codes` from src/accounting/vat-codes.ts and the English UI texts. Do not edit. -->',
    '',
    text('vatCodes.intro'),
    '',
    'The app shows the same catalogue in German, French, Italian and English: MWST tab, **Codes erklärt**, or a',
    'click on any code. There each code also lists the entries of the period that use it. Wherever the app shows',
    'or offers a code, it names it in plain words first (the Name column), the code beside it.',
    '',
    '## How to read a code',
    '',
    '- **The letters** name the family: V sale, VS discount on a sale, F flat tax rate, B acquisition tax,',
    '  M material and goods, I investments and operating costs, K corrections, Z money that is no consideration.',
    '- **The digits** are the rate times ten: 81 is 8.1%, 26 is 2.6%, 38 is 3.8%. 77, 25 and 37 are the rates until 2023.',
    '- **A minus** in front (-V81, -I81) makes a refund or reversal: the same boxes, and the amount counts negative.',
    '- **No suffix** on a code with a rate: the amount includes VAT, and the code takes the tax out of it.',
    '- **-1** after an input-tax or acquisition-tax code: the amount excludes VAT, and the tax is computed on top of it.',
    '- **-2**: the amount is the VAT itself, booked as a single-leg entry without a contra account.',
    '- **-B, -E, -N, -T, -D** on a sale code name the kind of supply (opted, abroad, not taxable, notification procedure, various).',
    '- **Boxes (Ziffern)** are the numbers of the ESTV return (form 0550). "turnover" means the gross amount counts in the box,',
    '  "taxable" that it is taxable turnover whose tax the rate row computes, "tax" that only the VAT in the amount counts.',
    '  The boxes below are what the app\'s engine books (`vat().report` over modules/ch), proven by tests/vat-codes.test.ts.',
    '- **Not declared**: the app puts the code into no box. Banana would; the column names Banana\'s boxes.',
    '',
    'The rules that choose a code are in `processes/booking.guide.yaml` (purchase_vat, sale_vat, side, eigenverbrauch);',
    'worked cases are in the [casebook](casebook.md).',
  ];

  for (const family of VAT_CODE_FAMILIES) {
    const kinds = VAT_CODE_KINDS.filter((k) => k.family === family);
    if (kinds.length === 0) continue;
    out.push('', `## ${family}: ${text(`vatCodes.family.${family}`)}`);
    for (const k of kinds) {
      const codes = VAT_CODES.filter((c) => c.kind === k.kind && c.family === k.family);
      if (codes.length === 0) continue;
      out.push('', `### ${text(`vatCodes.kind.${k.kind}.name`)}`, '',
        `**When:** ${text(`vatCodes.kind.${k.kind}.when`)}`, '',
        `**Not when:** ${text(`vatCodes.kind.${k.kind}.notWhen`)}`);
      if (k.rules.length) out.push('', `**Rules:** ${k.rules.map((r) => `\`${r}\``).join(', ')}`);
      out.push('', '| Code | Name | Banana text | Rate | Amount is | Boxes | Example |', '|---|---|---|---|---|---|---|');
      for (const c of codes) {
        const ex = c.examples[0];
        const example = ex ? `[${md(ex.title)}](../examples/cases/${ex.caseId}.yaml)` : '';
        out.push(`| ${c.code} | ${md(vatCodeName(c.code, text) ?? '')} | ${md(c.bananaText ?? '(not in Banana\'s list)')} | ${rateCell(c)} | ${amountCell(c)} | ${zifferCell(c)} | ${example} |`);
      }
    }
  }
  return `${out.join('\n')}\n`;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(SOURCE_FILE, renderSource());
  writeFileSync(DOCS_FILE, await renderDocs());
  console.log(`wrote ${SOURCE_FILE}\nwrote ${DOCS_FILE}`);
}
