/**
 * Writes docs/0.4.0/inventory.md (migration step 1): every file of src/ with its layer and the
 * Swiss specifics it names. `npm run inventory` rewrites it; tests/layers.test.ts fails when it is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LAYER_OF, layerOf, sourceFiles, type Layer } from './map.js';

/** What makes a line Swiss. Each one moves to modules/ch or src/providers by migration step 11. */
export const SWISS: [name: string, pattern: RegExp][] = [
  ['CHF', /\bCHF\b/],
  ['MWST', /\bMWST\b|Mehrwertsteuer/],
  ['ESTV', /\bESTV\b/],
  ['Ziffer', /\bZiffer/],
  ['tax code', /['"`]-?[VIMBK]\d{1,2}(?:-[12ABC])?['"`]/],
  ['eCH-0217', /eCH-?0217/],
  ['form 0535', /\b0535\b/],
  ['UID', /\bCHE-?\d{3}/],
  ['camt.053', /camt\.?053/i],
  ['QR-bill', /\bQR[- ]?(?:bill|Rechnung|IBAN|reference)|\bQRR\b/i],
  ['Rappen', /\bRappen\b/],
];

const ORDER: Layer[] = ['core', 'engine', 'provider', 'split', 'infrastructure', 'view'];

export function inventory(root: string): string {
  const files = sourceFiles(root).sort();
  const swissOf = (file: string) => {
    const lines = readFileSync(join(root, file), 'utf8').split('\n');
    return SWISS.map(([name, re]) => [name, lines.filter((l) => re.test(l)).length] as const).filter(([, n]) => n > 0);
  };
  const out = [
    '# Inventory',
    '',
    'Generated by `npm run inventory` from `tools/layers/map.ts`; do not edit by hand. Migration step 1',
    '([migration.md](migration.md)): every file of `src/` with its layer ([layers.md](layers.md)) and',
    'the Swiss specifics it names, counted in lines. `split` files hold generic logic and Swiss data',
    'together until step 10 takes them apart; step 11 forbids Swiss specifics outside `modules/ch/`',
    'and the providers.',
    '',
    '| Layer | Files | With Swiss specifics |',
    '|---|---:|---:|',
    ...ORDER.map((layer) => {
      const inLayer = files.filter((f) => layerOf(f) === layer);
      return `| ${layer} | ${inLayer.length} | ${inLayer.filter((f) => swissOf(f).length).length} |`;
    }),
    '',
    'Layers are assigned by path prefix, most specific first:',
    '',
    ...LAYER_OF.map(([prefix, layer]) => `- \`${prefix}\` → ${layer}`),
  ];
  for (const layer of ORDER) {
    const swiss = files.filter((f) => layerOf(f) === layer).map((f) => [f, swissOf(f)] as const).filter(([, s]) => s.length);
    if (!swiss.length) continue;
    out.push('', `## ${layer}`, '', '| File | Swiss specifics (lines) |', '|---|---|');
    for (const [file, s] of swiss) out.push(`| \`${file}\` | ${s.map(([name, n]) => `${name} ${n}`).join(', ')} |`);
  }
  return out.join('\n') + '\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = join(fileURLToPath(import.meta.url), '../../..');
  writeFileSync(join(root, 'docs/0.4.0/inventory.md'), inventory(root));
}
